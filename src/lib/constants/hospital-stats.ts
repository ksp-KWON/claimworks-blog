export function getHospitalCount(sido: string, gugun: string): number {
  const sidoData = HOSPITAL_STATS[sido] || {};
  if (sidoData[gugun]) return sidoData[gugun];
  
  const cleanGugun = gugun.replace(/^(인천|대구|광주|대전|울산|부산|서울)\s*/, '');
  for (const [k, v] of Object.entries(sidoData)) {
    if (k.includes(cleanGugun) || cleanGugun.includes(k)) return v;
  }
  return 0;
}

export function getTotalHospitalsInSido(sido: string): number {
  const sidoData = HOSPITAL_STATS[sido] || {};
  return Object.values(sidoData).reduce((sum, count) => sum + count, 0);
}
