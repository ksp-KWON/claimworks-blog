function determineArchetype(sido: string, gugun: string, stat: RegionHospitalStat): RegionArchetype {
  const fullKey = `${sido} ${gugun}`;
  const shortKey = `${sido.replace(/(특별시|광역시|특별자치시|도|특별자치도)/, '')} ${gugun}`;

  for (const ind of INDUSTRIAL_GUGUNS) {
    if (fullKey.includes(ind) || shortKey.includes(ind) || ind.includes(gugun)) {
      return 'INDUSTRIAL_TRAUMA';
    }
  }

  const hasTertiary = stat.majorHospitals.some(h => 
    TERTIARY_KEYWORDS.some(k => h.name.includes(k))
  );
  if (hasTertiary) {
    return 'TERTIARY_HUB';
  }

  const orthoNeuro = stat.orthoCount + stat.neurosurgeryCount + stat.rehabCount;
  if (orthoNeuro >= 8 || stat.totalCount >= 35) {
    return 'SPINE_JOINT_REHAB';
  }

  return 'COMMUNITY_PRIMARY';
}

function getJurisdiction(sido: string, gugun: string): JurisdictionInfo {
  const sidoMap = JURISDICTION_MAP[sido];
  if (sidoMap) {
    if (sidoMap[gugun]) return sidoMap[gugun];

    for (const [k, v] of Object.entries(sidoMap)) {
      if (gugun.startsWith(k) || k.startsWith(gugun)) {
        return v;
      }
    }
  }

  return {
    court: `${sido} 소재 관할 지방법원`,
    prosecution: `${sido} 소재 관할 검찰청`,
    highCourt: '관할 고등법원',
    courtType: '본원',
  };
}

// 아키텍처별 로컬 랭크 (순번)
const ARCHETYPE_LOCAL_RANK = new Map<string, number>();
const counters: Record<RegionArchetype, number> = {
  TERTIARY_HUB: 0,
  SPINE_JOINT_REHAB: 0,
  INDUSTRIAL_TRAUMA: 0,
  COMMUNITY_PRIMARY: 0,
};

for (const r of REGIONS_DATA) {
  for (const d of r.districts) {
    const { stat } = loadHospitalStat(r.name, d);
    const arch = determineArchetype(r.name, d, stat);
    const rank = counters[arch]++;
    ARCHETYPE_LOCAL_RANK.set(`${r.name}__${d}`, rank);
  }
}

