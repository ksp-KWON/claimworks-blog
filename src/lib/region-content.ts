  const archetype = determineArchetype(sido, gugun, hospitalStat);
  const jurisdiction = getJurisdiction(sido, gugun);

  const majorHospNames = hospitalStat.majorHospitals.map(h => h.name).join(', ') || '지역 거점 의료기관';
  const isHQ = jurisdiction.courtType === '본원';
  const pool = CONTENT_POOLS[archetype] || CONTENT_POOLS.COMMUNITY_PRIMARY;

  // 지역별 아키텍처 로컬 순번 (0 ~ N-1)
  const regionKey = `${sido}__${gugun}`;
  const k = ARCHETYPE_LOCAL_RANK.get(regionKey) ?? 0;

  // 중국인의 나머지 정리(CRT) 기반 소수 모듈러 조합: 어떤 두 지역도 동일한 문단 조합이 나올 수 없음
