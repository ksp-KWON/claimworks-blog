function getRegionCodes(sido: string, gugun: string): { sidoCode: string; gugunCode: string } | null {
  const sidoCode = standardData.TAAS_SIDO_CODES[sido as keyof typeof standardData.TAAS_SIDO_CODES];
  if (!sidoCode) return null;

  const gugunCodes = standardData.TAAS_GUGUN_CODES[sidoCode as keyof typeof standardData.TAAS_GUGUN_CODES] as Record<string, string> | undefined;
  if (!gugunCodes) return null;

  const cleanGugun = gugun.replace(/^(인천|대구|광주|대전|울산|부산|서울)\s*/, '');
  let gugunCode = gugunCodes[cleanGugun] || gugunCodes[gugun];

  if (!gugunCode) {
    const matchedKeys = Object.keys(gugunCodes)
      .filter(k => cleanGugun.includes(k) || k.includes(cleanGugun))
      .sort((a, b) => b.length - a.length);
    if (matchedKeys.length > 0) {
      gugunCode = gugunCodes[matchedKeys[0]];
    }
  }

  if (!gugunCode) {
    for (const [key, code] of Object.entries(gugunCodes)) {
      if (key.substring(0, 2) === cleanGugun.substring(0, 2)) {
        gugunCode = code;
        break;
      }
    }
  }

  return gugunCode ? { sidoCode, gugunCode } : null;
}

function loadHospitalStat(sido: string, gugun: string): { stat: RegionHospitalStat; codeToken: string } {
  const codes = getRegionCodes(sido, gugun);
  const defaultStat: RegionHospitalStat = {
    totalCount: 0,
    internalCount: 0,
    orthoCount: 0,
    neurosurgeryCount: 0,
    rehabCount: 0,
    majorHospitals: [],
  };

  if (!codes) return { stat: defaultStat, codeToken: '00-000' };

  const codeToken = `${codes.sidoCode}-${codes.gugunCode}`;
  const filePath = path.join(process.cwd(), 'public', 'data', 'hospitals', `${codeToken}.json`);
  let fileContent = '';

  if (fs.existsSync(filePath)) {
    fileContent = fs.readFileSync(filePath, 'utf-8');
  } else if (codes.sidoCode === '50') {
    const fallbackPath = path.join(process.cwd(), 'public', 'data', 'hospitals', `49-${codes.gugunCode}.json`);
    if (fs.existsSync(fallbackPath)) {
      fileContent = fs.readFileSync(fallbackPath, 'utf-8');
    }
  }

  if (!fileContent) return { stat: defaultStat, codeToken };

  try {
    const parsed = JSON.parse(fileContent);
    const specs = parsed.specialties || {};

    const getSpecCount = (key: string) => {
      const sp = specs[key];
      if (!sp) return 0;
      if (Array.isArray(sp)) return sp.length;
      return sp.count || (sp.hospitals ? sp.hospitals.length : 0);
    };

    const internalCount = getSpecCount('내과');
    const orthoCount = getSpecCount('정형외과');
    const neurosurgeryCount = getSpecCount('신경외과');
    const rehabCount = getSpecCount('재활의학과');

    const allHospitals: Array<{ name: string; address: string; tel: string }> = [];
    Object.values(specs).forEach((sp: any) => {
      if (sp && Array.isArray(sp.hospitals)) {
        sp.hospitals.forEach((h: any) => {
          if (h && h.name && !allHospitals.some(existing => existing.name === h.name)) {
            allHospitals.push(h);
          }
        });
      }
    });

    const sortedHospitals = allHospitals.sort((a, b) => {
      const isUnivA = a.name.includes('대학교') || a.name.includes('의료원') || a.name.includes('병원');
      const isUnivB = b.name.includes('대학교') || b.name.includes('의료원') || b.name.includes('병원');
      if (isUnivA && !isUnivB) return -1;
      if (!isUnivA && isUnivB) return 1;
      return 0;
    });

    return {
      stat: {
        totalCount: allHospitals.length,
        internalCount,
        orthoCount,
        neurosurgeryCount,
        rehabCount,
        majorHospitals: sortedHospitals.slice(0, 4),
      },
      codeToken,
    };
  } catch (err) {
    return { stat: defaultStat, codeToken };
  }
}

