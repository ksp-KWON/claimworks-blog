  const p1 = pool.p1[(k * 5 + 1) % pool.p1.length];
  const p2 = pool.p2[(k * 7 + 2) % pool.p2.length];
  const p3 = pool.p3[(k * 11 + 3) % pool.p3.length];
  const advice = pool.advices[(k * 13 + 4) % pool.advices.length];
  const summaryBullet = pool.summaries[(k * 17 + 5) % pool.summaries.length];

  const courtTemplates = isHQ ? COURT_ACTION_TEMPLATES.HQ : COURT_ACTION_TEMPLATES.BRANCH;
  const courtActionGuide = courtTemplates[(k * 3 + 1) % courtTemplates.length](jurisdiction, gugun);

  const statSentence = `총 ${hospitalStat.totalCount}개 의료기관(정형외과 ${hospitalStat.orthoCount}개소, 내과 ${hospitalStat.internalCount}개소, 신경외과 ${hospitalStat.neurosurgeryCount}개소, 재활의학과 ${hospitalStat.rehabCount}개소)`;
  const adminIdText = `[보건행정구역 코드 ${codeToken}]`;

